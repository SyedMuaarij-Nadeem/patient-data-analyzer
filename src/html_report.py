# ------------------------------------------------------------------------------
# Helper utilities
# ------------------------------------------------------------------------------

def _fmt(val, decimals=2):
    """Format a number, returning 'N/A' for NaN."""
    if val is None or (isinstance(val, float) and math.isnan(val)):
        return "N/A"
    if isinstance(val, int):
        return f"{val:,}"
    return f"{val:,.{decimals}f}"


def _pct(part, total):
    if total == 0:
        return 0.0
    return part / total * 100


def _coverage_color(pct):
    if pct >= 80:
        return "#3fb950"
    if pct >= 50:
        return "#e3b341"
    return "#f85149"


def _tab_button(key, label, active=False):
    cls = "tab-btn active" if active else "tab-btn"
    return f'    <button class="{cls}" data-tab="{key}" id="btn-{key}">{label}</button>'


def _tab_panel(key, content, active=False):
    cls = "tab-panel active" if active else "tab-panel"
    return f'  <section class="{cls}" id="tab-{key}" role="tabpanel">\n{content}\n  </section>'


