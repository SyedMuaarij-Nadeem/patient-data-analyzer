# ------------------------------------------------------------------------------
# Patient Assessment Mode Report
# ------------------------------------------------------------------------------

def generate_patient_report(
    output_path: str,
    patient: dict,
    assessments: list,
    statistics: dict,
    data: dict,
    chart_sample_size: int = 30_000,
):
    """Generate the personalised patient assessment HTML report."""
    now        = datetime.now().strftime("%B %d, %Y at %H:%M")
    name       = patient.get("name", "Unknown")
    age        = patient.get("age", "N/A")
    gender     = patient.get("gender", "N/A")
    gender_str = {"M": "Male", "F": "Female"}.get(gender, gender)

    # Sample data for chart overlays
    total_rows = max(len(v) for v in data.values()) if data else 0
    rng = np.random.default_rng(42)
    sample_idx = rng.choice(total_rows, size=min(chart_sample_size, total_rows), replace=False)
    sampled_data = {f: arr[sample_idx] for f, arr in data.items()}

    # -- Status summary card
    n_normal   = sum(1 for a in assessments if a["status_info"]["status"] == "normal")
    n_low      = sum(1 for a in assessments if "low" in a["status_info"]["status"])
    n_high     = sum(1 for a in assessments if "high" in a["status_info"]["status"])
    n_skipped  = sum(1 for a in assessments if a["status_info"]["status"] == "skipped")
    n_critical = sum(1 for a in assessments if "critical" in a["status_info"]["status"])

    # -- Vital cards
    vital_cards_html = ""
    for a in assessments:
        feature  = a["feature"]
        value    = a["value"]
        ref      = a["ref"]
        si       = a["status_info"]
        name_f   = ref.get("name", feature)
        unit     = ref.get("unit", "")
        min_n    = ref.get("min_normal", "")
        max_n    = ref.get("max_normal", "")
        desc     = ref.get("description", "")
        color    = si["color"]
        emoji    = si["emoji"]
        label    = si["label"]
        message  = si["message"]

        if value is None:
            val_display = "&mdash;"
            unit_display = ""
        else:
            val_display  = f"{value:.1f}"
            unit_display = unit

        vital_cards_html += f"""
        <div class="vital-card" style="--status-color:{color};">
          <div class="vc-head">
            <div class="vc-name">{emoji} {name_f}</div>
            <div class="vc-status">{label}</div>
          </div>
          <div class="vc-value">{val_display}</div>
          <div class="vc-unit">{unit_display}</div>
          <div class="vc-range">Normal range: {min_n}&ndash;{max_n} {unit}</div>
          <div class="vc-desc">{desc}</div>
          <div class="vc-msg">{message}</div>
        </div>"""

    # -- Charts with patient value overlays
    chart_html = ""
    for a in assessments:
        feature = a["feature"]
        value   = a["value"]
        ref     = REFERENCE_RANGES.get(feature)
        stats   = statistics.get(feature, {})
        arr     = sampled_data.get(feature)
        if arr is None or ref is None:
            continue
        fig = build_histogram(feature, arr, stats, ref, patient_value=value)
        chart_html += f'<div class="chart-wrap">{fig_to_html(fig)}</div>'

    # -- Overview panel
    overview_html = f"""
    <div class="stat-grid">
      <div class="stat-card"><div class="icon">&#9989;</div><div class="value" style="color:var(--green)">{n_normal}</div><div class="label">Normal Vitals</div></div>
      <div class="stat-card"><div class="icon">&#128308;</div><div class="value" style="color:var(--red)">{n_critical}</div><div class="label">Critically Out of Range</div></div>
      <div class="stat-card"><div class="icon">&#128993;</div><div class="value" style="color:var(--amber)">{n_low + n_high - n_critical}</div><div class="label">Borderline Values</div></div>
      <div class="stat-card"><div class="icon">&#8709;</div><div class="value" style="color:var(--text-dim)">{n_skipped}</div><div class="label">Not Provided</div></div>
    </div>

    <div class="plain-box">
      <h3>&#128100; Patient: {name}</h3>
      <p>Age: <strong>{age}</strong> years &bull; Gender: <strong>{gender_str}</strong> &bull; Assessed: <strong>{now}</strong></p>
    </div>

    {f'<div class="alert alert-danger">&#9888;&#65039; <strong>Attention:</strong> One or more measurements are critically outside the normal range. Please consult a healthcare professional immediately.</div>' if n_critical > 0 else ''}
    {f'<div class="alert alert-warn">&#9888;&#65039; <strong>Note:</strong> Some measurements are outside the normal range. Please discuss these results with a healthcare professional.</div>' if (n_low + n_high - n_critical) > 0 else ''}
    {f'<div class="alert alert-info">&#9989; <strong>All provided measurements are within normal ranges.</strong> Continue to follow your healthcare provider guidance.</div>' if n_normal == len(assessments) - n_skipped and n_low + n_high == 0 else ''}"""

    # -- Vital signs panel
    vitals_html = f"""
    <div class="alert alert-info">
      &#128218; Each card shows a traffic-light status. Normal values are shown in green,
      borderline in amber, and out-of-range values in red. Each card also explains
      what the measurement means in plain language.
    </div>
    <div class="vital-grid">{vital_cards_html}</div>"""

    # -- Charts panel
    charts_section_html = f"""
    <div class="alert alert-info">
      &#128200; Each chart shows the distribution of that vital sign across the hospital patient dataset.
      The <strong>vertical colored line</strong> marks the patient's own value.
      The <strong>green shaded area</strong> shows the clinical normal range.
    </div>
    <div class="chart-grid">{chart_html}</div>"""

    # -- Banner
    banner_html = f"""<header class="banner">
  <span class="banner-icon">&#128100;</span>
  <h1>Patient Vital Sign Assessment</h1>
  <p class="subtitle">{name} &bull; Age {age} &bull; {gender_str}</p>
  <span class="badge badge-patient">Patient Assessment Mode</span>
</header>"""

    tab_buttons = "\n".join([
        _tab_button("overview", "&#127968; Summary",        active=True),
        _tab_button("vitals",   "&#10084;&#65039; Vital Signs", active=False),
        _tab_button("charts",   "&#128200; Population Charts",  active=False),
    ])
    tab_panels = "\n".join([
        _tab_panel("overview", overview_html,       active=True),
        _tab_panel("vitals",   vitals_html,         active=False),
        _tab_panel("charts",   charts_section_html, active=False),
    ])

    html = HTML_TEMPLATE.format(
        page_title   = f"Patient Report: {name}",
        banner_html  = banner_html,
        tab_buttons  = tab_buttons,
        tab_panels   = tab_panels,
        generated_at = now,
    )

    import os
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(html)

    print(f"  Patient HTML report saved: {output_path}")
