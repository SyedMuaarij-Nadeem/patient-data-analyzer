def generate_dataset_report(
    output_path: str,
    patients: list,
    unique_patients: set,
    statistics: dict,
    missing_data: dict,
    duplicates: int,
    invalid_values: list,
    anomalies: list,
    correlations: dict,
    data: dict,
    sepsis_labels: np.ndarray | None = None,
    chart_sample_size: int = 30_000,
):
    """Generate the full-dataset HTML report."""
    total_rows = len(patients)
    total_missing = sum(missing_data.values())
    now = datetime.now().strftime("%B %d, %Y at %H:%M")

    # -- Sample indices for charts
    rng = np.random.default_rng(42)
    sample_idx = rng.choice(total_rows, size=min(chart_sample_size, total_rows), replace=False)
    sampled_data = {f: arr[sample_idx] for f, arr in data.items()}

    # -- Anomaly counts per feature
    anomaly_counts = {}
    for a in anomalies:
        f = a["feature"]
        anomaly_counts[f] = anomaly_counts.get(f, 0) + 1

    # -- Build charts
    histograms    = {}
    for feature, arr in sampled_data.items():
        ref  = REFERENCE_RANGES.get(feature)
        stat = statistics.get(feature, {})
        histograms[feature] = fig_to_html(build_histogram(feature, arr, stat, ref))

    corr_heatmap  = fig_to_html(build_correlation_heatmap(correlations))
    missing_chart = fig_to_html(build_missing_data_chart(missing_data, total_rows))
    anomaly_chart = fig_to_html(build_anomaly_bar_chart(anomaly_counts))
    sepsis_chart  = fig_to_html(build_sepsis_comparison(data, sepsis_labels)) if sepsis_labels is not None else None
    gender_chart  = fig_to_html(build_gender_breakdown(sampled_data, [patients[i] for i in sample_idx], list(data.keys())))

    # -- Panels --------------------------------------------------------------

    # 1. Overview Panel
    coverage_pct = 100 - _pct(total_missing, total_rows * len(statistics))
    overview_html = f"""
    <div class="stat-grid">
      <div class="stat-card"><div class="icon">&#128203;</div><div class="value">{total_rows:,}</div><div class="label">Total Observations</div></div>
      <div class="stat-card"><div class="icon">&#128100;</div><div class="value">{len(unique_patients):,}</div><div class="label">Unique Patients</div></div>
      <div class="stat-card"><div class="icon">&#9889;</div><div class="value">{duplicates:,}</div><div class="label">Duplicate Rows</div></div>
      <div class="stat-card"><div class="icon">&#128202;</div><div class="value">{len(anomalies):,}</div><div class="label">Statistical Anomalies</div></div>
      <div class="stat-card"><div class="icon">&#9989;</div><div class="value">{coverage_pct:.1f}%</div><div class="label">Data Coverage</div></div>
    </div>

    <div class="plain-box">
      <h3>&#128218; What Does This Report Show?</h3>
      <p>
        This report analyses a clinical dataset from <strong>{len(unique_patients):,} hospital patients</strong>
        across <strong>{total_rows:,} hourly observations</strong>. It examines vital signs such as heart rate,
        blood pressure, oxygen levels, and glucose to identify patterns, data gaps, and statistically
        unusual values. It does <strong>not</strong> diagnose any patient.
      </p>
    </div>

    <div class="alert alert-info">
      &#8505;&#65039; Charts in this report are generated from a random sample of
      <strong>{min(chart_sample_size, total_rows):,} rows</strong> for performance.
      All statistics (mean, std, etc.) are computed on the full dataset.
    </div>"""

    # 2. Technical Panel — for clinicians/doctors
    stat_rows = ""
    for feature, stats in statistics.items():
        ref  = REFERENCE_RANGES.get(feature, {})
        name = ref.get("name", feature)
        unit = ref.get("unit", "")
        cnt  = stats["count"]
        cov  = _pct(cnt, total_rows)
        miss = missing_data.get(feature, 0)
        anom = anomaly_counts.get(feature, 0)
        anom_pct = _pct(anom, cnt) if cnt > 0 else 0
        color = _coverage_color(cov)
        stat_rows += f"""
        <tr>
          <td><strong>{name}</strong><br><span style='color:var(--text-dim);font-size:11px;'>{feature} &bull; {unit}</span></td>
          <td class="num">{cnt:,}</td>
          <td>
            <div class="progress-wrap">
              <span style="color:{color};font-weight:600;">{cov:.1f}%</span>
              <div class="progress-bar"><div class="progress-fill" style="width:{cov:.1f}%;background:{color};"></div></div>
            </div>
          </td>
          <td class="num">{_fmt(stats.get('mean'))}</td>
          <td class="num">{_fmt(stats.get('median'))}</td>
          <td class="num">{_fmt(stats.get('std'))}</td>
          <td class="num">{_fmt(stats.get('minimum'))}</td>
          <td class="num">{_fmt(stats.get('maximum'))}</td>
          <td class="num">{miss:,} ({_pct(miss,total_rows):.1f}%)</td>
          <td class="num" style="color:{'var(--red)' if anom_pct>5 else 'var(--amber)' if anom_pct>1 else 'var(--green)'}">{anom:,} ({anom_pct:.1f}%)</td>
        </tr>"""

    corr_rows = ""
    for pair, val in correlations.items():
        if math.isnan(val):
            strength, color = "N/A", "var(--text-dim)"
        else:
            abs_val = abs(val)
            if abs_val >= 0.7:   strength, color = "Strong",   "var(--red)"
            elif abs_val >= 0.4: strength, color = "Moderate", "var(--amber)"
            elif abs_val >= 0.2: strength, color = "Weak",     "var(--blue)"
            else:                strength, color = "Negligible","var(--text-dim)"
        corr_rows += f"""
        <tr>
          <td>{pair}</td>
          <td class="num">{_fmt(val, 3)}</td>
          <td style="color:{color};font-weight:500;">{strength}</td>
        </tr>"""

    technical_html = f"""
    <div class="section-title"><span class="icon">&#128203;</span> Feature Statistics (Full Dataset)</div>
    <div class="table-wrap">
      <table class="data-table">
        <thead><tr>
          <th>Feature</th><th>Count</th><th>Coverage</th>
          <th>Mean</th><th>Median</th><th>Std Dev</th>
          <th>Min</th><th>Max</th><th>Missing</th><th>Anomalies</th>
        </tr></thead>
        <tbody>{stat_rows}</tbody>
      </table>
    </div>

    <div class="section-title" style="margin-top:32px;"><span class="icon">&#128202;</span> Correlation Analysis</div>
    <div class="chart-grid">
      <div class="chart-wrap">{corr_heatmap}</div>
    </div>
    <div class="table-wrap">
      <table class="data-table">
        <thead><tr><th>Pair</th><th>Pearson r</th><th>Strength</th></tr></thead>
        <tbody>{corr_rows}</tbody>
      </table>
    </div>

    <div class="section-title" style="margin-top:32px;"><span class="icon">&#9888;&#65039;</span> Anomaly Summary</div>
    <div class="chart-wrap">{anomaly_chart}</div>
    <div class="alert alert-warn">
      &#9888;&#65039; A statistical anomaly means a value is more than 2 standard deviations from the dataset mean.
      This is a statistical flag, not a clinical diagnosis. Many anomalies are expected in large datasets.
    </div>

    <div class="section-title" style="margin-top:32px;"><span class="icon">&#128200;</span> Data Completeness</div>
    <div class="chart-wrap">{missing_chart}</div>"""

    # 3. Plain English Panel — for guardians/patients
    plain_vitals = ""
    for feature in statistics:
        ref   = REFERENCE_RANGES.get(feature)
        if not ref:
            continue
        stats = statistics[feature]
        name  = ref["name"]
        unit  = ref["unit"]
        desc  = ref["description"]
        min_n = ref["min_normal"]
        max_n = ref["max_normal"]
        mean_val = stats.get("mean", float("nan"))
        mean_str = _fmt(mean_val)

        # Is the dataset average normal?
        if not math.isnan(mean_val) and min_n <= mean_val <= max_n:
            avg_note = f"The average value in this dataset ({mean_str} {unit}) is within the normal range ({min_n}&#8211;{max_n} {unit})."
            avg_color = "var(--green)"
        elif math.isnan(mean_val):
            avg_note = "Average not available due to missing data."
            avg_color = "var(--text-dim)"
        else:
            avg_note = f"The average value in this dataset ({mean_str} {unit}) is outside the typical normal range ({min_n}&#8211;{max_n} {unit}). This may reflect the hospital patient population studied."
            avg_color = "var(--amber)"

        plain_vitals += f"""
        <details class="collapsible">
          <summary><span>&#10024;</span> {name} &mdash; <span style="color:var(--text-dim);font-size:12px;">click to learn more</span></summary>
          <div class="collapsible-body">
            <div class="plain-box">
              <h3>What is {name}?</h3>
              <p>{desc}</p>
            </div>
            <div class="plain-box" style="border-left-color:{avg_color};">
              <h3>Dataset Average</h3>
              <p>{avg_note}</p>
              <p style="margin-top:8px;">Normal range: <strong>{min_n} &#8211; {max_n} {unit}</strong></p>
            </div>
            <div class="chart-wrap">{histograms.get(feature, '')}</div>
          </div>
        </details>"""

    plain_html = f"""
    <div class="alert alert-info">
      &#128218; This section explains the medical measurements in plain language.
      It is designed for patients, families, and non-medical readers.
    </div>

    <div class="plain-box">
      <h3>&#128105;&#8205;&#127979; Who Are These Patients?</h3>
      <p>
        This dataset comes from <strong>{len(unique_patients):,} real hospital patients</strong> admitted to an ICU
        (Intensive Care Unit). Their vital signs were recorded every hour. The average patient age is
        approximately <strong>{_fmt(statistics.get('Age', {}).get('mean', float('nan')), 0)} years</strong>.
        This dataset is used for research into sepsis — a life-threatening response to infection.
      </p>
    </div>

    <div class="section-title"><span class="icon">&#10067;</span> Understanding Each Measurement</div>
    {plain_vitals}"""

    # 4. Charts Panel
    hist_html = ""
    for feature, chart_div in histograms.items():
        ref  = REFERENCE_RANGES.get(feature, {})
        name = ref.get("name", feature)
